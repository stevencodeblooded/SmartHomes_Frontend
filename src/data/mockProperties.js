/**
 * Helper functions for working with mock properties
 */

// Get property by ID
export const getPropertyById = (id) => {
  return MOCK_PROPERTIES.find((property) => property.id === id) || null;
};

// Get featured properties
export const getFeaturedProperties = () => {
  return MOCK_PROPERTIES.filter((property) => property.featured);
};

// Get properties by location
export const getPropertiesByLocation = (city, neighborhood = null) => {
  return MOCK_PROPERTIES.filter((property) => {
    const matchesCity =
      property.location.city.toLowerCase() === city.toLowerCase();
    if (neighborhood) {
      const matchesNeighborhood =
        property.location.neighborhood.toLowerCase() ===
        neighborhood.toLowerCase();
      return matchesCity && matchesNeighborhood;
    }
    return matchesCity;
  });
};

// Get properties by type
export const getPropertiesByType = (propertyType) => {
  return MOCK_PROPERTIES.filter(
    (property) => property.propertyType === propertyType,
  );
};

// Get properties by rental type
export const getPropertiesByRentalType = (rentalType) => {
  return MOCK_PROPERTIES.filter(
    (property) =>
      property.rentalType === rentalType || property.rentalType === "both",
  );
};

// Get properties by host
export const getPropertiesByHost = (hostId) => {
  return MOCK_PROPERTIES.filter((property) => property.host.id === hostId);
};

// Get total count
export const getTotalProperties = () => {
  return MOCK_PROPERTIES.length;
};

export default {
  MOCK_PROPERTIES,
  getPropertyById,
  getFeaturedProperties,
  getPropertiesByLocation,
  getPropertiesByType,
  getPropertiesByRentalType,
  getPropertiesByHost,
  getTotalProperties,
};
